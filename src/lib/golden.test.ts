import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { buildSchedule, type PlanInput } from './schedule'

/**
 * Golden schedules. Correctness is established by the hand-checked tests in schedule.test.ts / emi.test.ts;
 * this file freezes the exact rows so (a) refactors cannot change them silently and (b) Phase 5's SQL functions
 * can be run against the very same inputs and compared row by row.
 * Regenerate deliberately with: UPDATE_GOLDEN=1 pnpm vitest run src/lib/golden.test.ts
 */
const FILE = 'tests/fixtures/schedule-cases.json'

const CASES: { name: string; input: PlanInput }[] = [
  { name: 'B: borrowed 50,000 in 10 monthly from 5 Dec', input: { mode: 'equal', principal: 5_000_000, count: 10, firstDate: '2026-12-05' } },
  { name: 'C: store EMI 60,000 less 6,000 down, 9 months no-cost from 10 Dec', input: { mode: 'reducing', principal: 5_400_000, count: 9, firstDate: '2026-12-10', rateBps: 1500, noCost: true } },
  { name: 'D: lent 2,000 in 4 weekly', input: { mode: 'equal', principal: 200_000, count: 4, firstDate: '2026-03-01', period: 'weekly' } },
  { name: 'month-end clamp, 5 monthly from 31 Oct', input: { mode: 'equal', principal: 900_000, count: 5, firstDate: '2026-10-31' } },
  { name: 'leap-year clamp from 31 Jan 2028', input: { mode: 'equal', principal: 300_000, count: 3, firstDate: '2028-01-31' } },
  { name: 'rounding: 10,000 in 3 (remainder on last row)', input: { mode: 'equal', principal: 1_000_000, count: 3, firstDate: '2026-01-10' } },
  { name: 'flat 10% on 10,000 over 5', input: { mode: 'equal', principal: 1_000_000, count: 5, firstDate: '2026-01-01', interest: 'flat', rateBps: 1000 } },
  { name: 'simple 12% p.a. on 12,000 over 12 months', input: { mode: 'equal', principal: 1_200_000, count: 12, firstDate: '2026-01-01', interest: 'simple', rateBps: 1200 } },
  { name: 'simple 10% p.a. weekly over 52 weeks', input: { mode: 'equal', principal: 520_000, count: 52, firstDate: '2026-01-01', period: 'weekly', interest: 'simple', rateBps: 1000 } },
  { name: 'reducing 12% on 1,00,000 over 12 months', input: { mode: 'reducing', principal: 10_000_000, count: 12, firstDate: '2026-01-15', rateBps: 1200 } },
  { name: 'reducing 10% on 5,00,000 over 60 months', input: { mode: 'reducing', principal: 50_000_000, count: 60, firstDate: '2026-01-31', rateBps: 1000 } },
  { name: 'installment 12,000 by 5,000', input: { mode: 'installment', principal: 1_200_000, amount: 500_000, firstDate: '2026-01-01' } },
  { name: 'installment flat 10% on 10,000 by 5,000', input: { mode: 'installment', principal: 1_000_000, amount: 500_000, firstDate: '2026-01-01', interest: 'flat', rateBps: 1000 } },
  { name: 'custom dates with flat interest', input: { mode: 'custom', principal: 1_000_000, dates: ['2026-01-05', '2026-02-20', '2026-06-01'], interest: 'flat', rateBps: 1000 } },
]

const cases = CASES.map(({ name, input }) => {
  const r = buildSchedule(input)
  return {
    name, input,
    expected: {
      total_payable_paise: r.total_payable_paise,
      total_interest_paise: r.total_interest_paise,
      rows: r.rows.map(({ seq, due_date, due_paise, principal_paise, interest_paise }) => ({ seq, due_date, due_paise, principal_paise, interest_paise })),
    },
  }
})

describe('golden schedules', () => {
  if (process.env.UPDATE_GOLDEN) {
    it('writes the fixture', () => {
      writeFileSync(FILE, JSON.stringify({ _note: 'Generated by src/lib/golden.test.ts. Phase 5 SQL tests must reproduce these rows.', cases }, null, 2) + '\n')
    })
    return
  }
  it('fixture exists', () => expect(existsSync(FILE)).toBe(true))
  it('matches the frozen rows exactly', () => {
    const frozen = JSON.parse(readFileSync(FILE, 'utf8')) as { cases: typeof cases }
    expect(frozen.cases).toEqual(cases)
  })
})
